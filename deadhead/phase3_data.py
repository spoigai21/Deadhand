"""Phase 3: the tables a Java worker reads instead of carrying an H3 library, plus the stream topics it consumes.

Exports into data/phase3/ (gitignored; regenerated by this script):
  fleet_<day>_N<n>_seed<s>.json   the initial fleet, identical to the oracle's (same RNG draw from the same dropoff pool)
  cells_<day>.json                for every resolution-8 cell a driver or pickup can sit in: ring-3 and ring-5 disks (sorted),
                                  parents at resolutions 5, 6 and 7
  demand_<day>.json               hour -> cell -> real pickup points sorted by (lon, lat): the cruise targets, hour 23 from the day before
Then re-produces requests-<day> (resolution-6 key) with the cells in each record, and requests-<day>-k7 (resolution-7 key).

Usage: python -m deadhead.phase3_data configs/phase3.yaml [day ...]
"""
import json, sys, zlib
from pathlib import Path
import h3, polars as pl, yaml
from .data import load_week, day_requests, PU_DT, DO_DT
from .fleet import Fleet
from .stream import produce_day

def partition_of(key, partitions):
    """The partition the producers' default partitioner gives a string key: CRC32 modulo the count."""
    return zlib.crc32(key.encode()) % partitions

def export(cfg, day):
    out = Path("data/phase3"); out.mkdir(parents=True, exist_ok=True)
    week = load_week(cfg["trips_dir"]); res = cfg["h3_resolution"]
    day_start = float(pl.Series([day]).str.to_datetime().dt.epoch("s")[0])
    for seed in cfg["seeds"]:
        fleet, _ = Fleet.from_dropoffs(week, day, cfg["fleet_size"], cfg["initial_positions_window_s"], seed, res, cfg["ring_k"], cfg["cruise_after_s"], day_start)
        rows = [[d, float(fleet.lon[d]), float(fleet.lat[d]), f"{int(fleet.cell[d]):x}"] for d in range(fleet.n)]
        (out / f"fleet_{day}_N{cfg['fleet_size']}_seed{seed}.json").write_text(json.dumps({"day": day, "day_start": day_start, "seed": seed, "drivers": rows}))
    # every cell a driver can occupy: the day's pickups and dropoffs, and the dropoffs of the hour before midnight
    d = day_requests(week, day)
    start = pl.lit(day).str.to_datetime() - pl.duration(seconds=cfg["initial_positions_window_s"]); end = pl.lit(day).str.to_datetime() + pl.duration(hours=23)
    pool = week.filter((pl.col(DO_DT) >= start) & (pl.col(DO_DT) < pl.lit(day).str.to_datetime()))
    prev = week.filter((pl.col(PU_DT) >= pl.lit(day).str.to_datetime() - pl.duration(hours=1)) & (pl.col(PU_DT) < pl.lit(day).str.to_datetime()))
    cells = set()
    for df, lon, lat in ((d, "pickup_longitude", "pickup_latitude"), (d, "dropoff_longitude", "dropoff_latitude"), (pool, "dropoff_longitude", "dropoff_latitude"), (prev, "pickup_longitude", "pickup_latitude")):
        cells.update(h3.latlng_to_cell(la, lo, res) for lo, la in zip(df[lon].to_list(), df[lat].to_list()))
    table = {}
    for c in sorted(cells):
        table[c] = {"d3": sorted(h3.grid_disk(c, cfg["ring_k"]), key=lambda x: int(x, 16)), "d5": sorted(h3.grid_disk(c, cfg["cruise_ring_k"]), key=lambda x: int(x, 16)),
                    "p5": h3.cell_to_parent(c, 5), "p6": h3.cell_to_parent(c, 6), "p7": h3.cell_to_parent(c, 7)}
    (out / f"cells_{day}.json").write_text(json.dumps({"day": day, "resolution": res, "cells": table}))
    # the cruise demand map, exactly the oracle's with cruise_point: hash (hour 23 = the previous day's; BUGS.md #3)
    pk = week.filter((pl.col(PU_DT) >= pl.lit(day).str.to_datetime() - pl.duration(hours=1)) & (pl.col(PU_DT) < end)).sort("pickup_longitude", "pickup_latitude")
    pk = pk.with_columns(pl.col(PU_DT).dt.hour().alias("hour"))
    demand = {}
    for h, lon, lat in zip(pk["hour"].to_list(), pk["pickup_longitude"].to_list(), pk["pickup_latitude"].to_list()):
        demand.setdefault(str(h), {}).setdefault(h3.latlng_to_cell(lat, lon, res), []).append([lon, lat])
    (out / f"demand_{day}.json").write_text(json.dumps({"day": day, "hours": demand}))
    # the partition map: which partition each key cell lands in, for the record and for a test
    parts = {}
    for r in sorted({cfg["key_resolution"], *cfg.get("key_resolution_sensitivity", [])} | set(cfg.get("shard_key_resolutions", []))):
        keys = sorted({h3.cell_to_parent(c, r) for c in cells})
        parts[str(r)] = {k: partition_of(k, cfg["partitions"]) for k in keys}
    (out / f"partitions_{day}.json").write_text(json.dumps({"day": day, "partitions": cfg["partitions"], "by_key_resolution": parts}))
    return {"day": day, "cells": len(table), "demand_points": pk.height, "fleet_seeds": cfg["seeds"]}

if __name__ == "__main__":
    cfg = yaml.safe_load(open(sys.argv[1]))
    for day in sys.argv[2:] or cfg["days"]:
        print(json.dumps(export(cfg, day)), flush=True)
        for r in [cfg["key_resolution"], *cfg.get("key_resolution_sensitivity", [])]:
            print(json.dumps(produce_day({**cfg, "key_resolution": r}, day)), flush=True)
